export YAM_POLICY_OBJECT_X_RANGE="${YAM_POLICY_OBJECT_X_RANGE:--0.34 -0.24}"
export YAM_POLICY_OBJECT_Y_RANGE="${YAM_POLICY_OBJECT_Y_RANGE:--0.34 -0.22}"
export YAM_POLICY_BIN_X_RANGE="${YAM_POLICY_BIN_X_RANGE:--0.34 -0.10}"
export YAM_POLICY_BIN_Y_RANGE="${YAM_POLICY_BIN_Y_RANGE:-0.08 0.30}"
