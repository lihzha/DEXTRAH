export DEMO_STEPS_PER_OBJECT="${DEMO_STEPS_PER_OBJECT:-900}"
export MAX_ATTEMPTS="${MAX_ATTEMPTS:-180}"
export NUM_GRASPS="${NUM_GRASPS:-192}"
export TOPK="${TOPK:-96}"
export MAX_PLAN_ATTEMPTS="${MAX_PLAN_ATTEMPTS:-96}"
export YAM_GRASP_FILTER_MIN_KEEP="${YAM_GRASP_FILTER_MIN_KEEP:-4}"
export YAM_ALLOW_LIFT_FILTER_FALLBACK="${YAM_ALLOW_LIFT_FILTER_FALLBACK:-False}"
export POOL_MAX_ASSETS="${POOL_MAX_ASSETS:-512}"
export POOL_MAX_XY_RADIUS="${POOL_MAX_XY_RADIUS:-0.055}"
export POOL_MAX_GRASP_WIDTH_P95="${POOL_MAX_GRASP_WIDTH_P95:-0.110}"
export POOL_MIN_XY_HALF_EXTENT="${POOL_MIN_XY_HALF_EXTENT:-0.020}"
export POOL_MIN_Z_HALF_EXTENT="${POOL_MIN_Z_HALF_EXTENT:-0.032}"
export POOL_MAX_XY_ASPECT="${POOL_MAX_XY_ASPECT:-1.8}"

# Keep the generated motion more continuous than the earlier visualization
# demos while retaining enough samples through lift/transport/drop.
export SCRIPTED_LIFT_HEIGHT="${SCRIPTED_LIFT_HEIGHT:-0.13}"
export SCRIPTED_LIFT_FRAMES="${SCRIPTED_LIFT_FRAMES:-120}"
export MOVE_TO_BIN_FRAMES="${MOVE_TO_BIN_FRAMES:-220}"
export START_GUARD_FRAMES="${START_GUARD_FRAMES:-12}"
export CLOSE_FRAMES="${CLOSE_FRAMES:-36}"
export HOLD_FRAMES="${HOLD_FRAMES:-12}"
export HOLD_AFTER_CLOSE_FRAMES="${HOLD_AFTER_CLOSE_FRAMES:-24}"
export RETURN_TO_START_FRAMES="${RETURN_TO_START_FRAMES:-60}"
export DROP_HEIGHT_ABOVE_BIN="${DROP_HEIGHT_ABOVE_BIN:-0.14}"
export SCRIPTED_BIN_DROP_Y_OFFSET="${SCRIPTED_BIN_DROP_Y_OFFSET:-0.0}"
export SCRIPTED_BIN_DROP_Y_OFFSET_AFTER_FIRST="${SCRIPTED_BIN_DROP_Y_OFFSET_AFTER_FIRST:-0.0}"

export OBJECT_SPAWN_XY_RANDOMIZATION="${OBJECT_SPAWN_XY_RANDOMIZATION:-0.0}"
export TABLETOP_CLUTTER_SPAWN_XY_RANDOMIZATION="${TABLETOP_CLUTTER_SPAWN_XY_RANDOMIZATION:-0.0}"
export TABLETOP_CLUTTER_MAX_OBJECTS="${TABLETOP_CLUTTER_MAX_OBJECTS:-0}"
export TABLETOP_CLUTTER_OBJECT_COUNT="${TABLETOP_CLUTTER_OBJECT_COUNT:-0}"
export TABLETOP_CLUTTER_ASSET_ASSIGNMENT="${TABLETOP_CLUTTER_ASSET_ASSIGNMENT:-random_without_replacement}"
