export YAM_POLICY_BIN_WALL_HEIGHT_RANGE="${YAM_POLICY_BIN_WALL_HEIGHT_RANGE:-0.08 0.16}"
export YAM_POLICY_SCENE_CAMERA_EYE_JITTER="${YAM_POLICY_SCENE_CAMERA_EYE_JITTER:-0.05 0.07 0.05}"
export YAM_POLICY_SCENE_CAMERA_TARGET_JITTER="${YAM_POLICY_SCENE_CAMERA_TARGET_JITTER:-0.04 0.05 0.03}"
export YAM_POLICY_DOME_LIGHT_INTENSITY_RANGE="${YAM_POLICY_DOME_LIGHT_INTENSITY_RANGE:-450 1600}"
export YAM_POLICY_KEY_LIGHT_INTENSITY_RANGE="${YAM_POLICY_KEY_LIGHT_INTENSITY_RANGE:-250 1400}"
export YAM_POLICY_MATERIAL_VALUE_RANGE="${YAM_POLICY_MATERIAL_VALUE_RANGE:-0.32 0.82}"

echo "Launching single-object YAM policy demo collection through shared collector"
echo "BATCH_NAME=$BATCH_NAME"
echo "BATCH_DIR=$BATCH_DIR"
echo "TOTAL_TARGET=$TOTAL_TARGET"
echo "OBJECT_X_RANGE=$YAM_POLICY_OBJECT_X_RANGE"
echo "OBJECT_Y_RANGE=$YAM_POLICY_OBJECT_Y_RANGE"
echo "BIN_Y_RANGE=$YAM_POLICY_BIN_Y_RANGE"
echo "POOL_MAX_ASSETS=$POOL_MAX_ASSETS"
echo "POOL_MAX_XY_RADIUS=$POOL_MAX_XY_RADIUS"
echo "POOL_MAX_GRASP_WIDTH_P95=$POOL_MAX_GRASP_WIDTH_P95"
echo "POOL_MIN_XY_HALF_EXTENT=$POOL_MIN_XY_HALF_EXTENT"
echo "POOL_MIN_Z_HALF_EXTENT=$POOL_MIN_Z_HALF_EXTENT"
echo "POOL_MAX_XY_ASPECT=$POOL_MAX_XY_ASPECT"
echo "MAX_ATTEMPTS=$MAX_ATTEMPTS"
echo "MOTION_TIMING=start_guard:$START_GUARD_FRAMES close:$CLOSE_FRAMES hold:$HOLD_FRAMES after_close:$HOLD_AFTER_CLOSE_FRAMES lift:$SCRIPTED_LIFT_FRAMES bin:$MOVE_TO_BIN_FRAMES return:$RETURN_TO_START_FRAMES"

exec bash "$CODE_NFS/cluster/sbatch_collect_yam_objaverse_demos_1gpu.sh"
