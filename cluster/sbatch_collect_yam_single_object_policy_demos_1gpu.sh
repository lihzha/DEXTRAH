#!/bin/bash
#SBATCH --nodes=1
#SBATCH --ntasks=1
#SBATCH --account=nvr_lpr_rvp
#SBATCH --gpus-per-node=1
#SBATCH --job-name=yam_policy_demo
#SBATCH --partition=batch_singlenode,grizzly,polar,polar3,polar4,interactive_singlenode
#SBATCH --time=0-03:50:00
#SBATCH --mem=160G
#SBATCH --cpus-per-task=16
#SBATCH --output=/lustre/fsw/portfolios/nvr/users/lzha/slurm_logs/dextrah/yam_policy_demo_%j.out

set -euo pipefail

NFS_ROOT="${NFS_ROOT:-/lustre/fsw/portfolios/nvr/users/lzha}"
CODE_NFS="${CODE_NFS:-$NFS_ROOT/src/DEXTRAH}"
RESULTS_NFS="${RESULTS_NFS:-$NFS_ROOT/results/dextrah}"

export NFS_ROOT CODE_NFS RESULTS_NFS

# Coordinate convention: Y is the long/right-left table axis.  Robot right is
# -Y, robot left is +Y, and the YAM forward/back direction is X.
export TOTAL_TARGET="${TOTAL_TARGET:-500}"
export BATCH_NAME="${BATCH_NAME:-yam_single_object_policy_500_$(date -u +%Y%m%dT%H%M%SZ)}"
export BATCH_DIR="${BATCH_DIR:-$RESULTS_NFS/yam_demos/$BATCH_NAME}"
export OBJECTS_PER_DEMO="${OBJECTS_PER_DEMO:-1}"
export OBJECTS_PER_DEMO_MIN="${OBJECTS_PER_DEMO_MIN:-1}"
export OBJECTS_PER_DEMO_MAX="${OBJECTS_PER_DEMO_MAX:-1}"

export SETTLE_STEPS="${SETTLE_STEPS:-100}"
export SETTLE_CAPTURE_INTERVAL="${SETTLE_CAPTURE_INTERVAL:-20}"
export REPLAY_CAPTURE_INTERVAL="${REPLAY_CAPTURE_INTERVAL:-10}"
export FPS="${FPS:-12}"
export RECORD_RGB_WIDTH="${RECORD_RGB_WIDTH:-160}"
export RECORD_RGB_HEIGHT="${RECORD_RGB_HEIGHT:-120}"
export RECORD_RGB_INTERVAL="${RECORD_RGB_INTERVAL:-4}"
export RECORD_MULTICAM_RGB="${RECORD_MULTICAM_RGB:-False}"
export RECORD_SCENE_RGB="${RECORD_SCENE_RGB:-True}"
export RECORD_WRIST_RGB="${RECORD_WRIST_RGB:-False}"
