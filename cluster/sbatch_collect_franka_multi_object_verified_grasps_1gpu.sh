import json
import sys

path = sys.argv[1]
target = int(sys.argv[2])
with open(path, "r", encoding="utf-8") as f:
    payload = json.load(f)
counts = payload.get("summary", {}).get("counts_by_uuid", {})
missing = {uuid: int(count) for uuid, count in counts.items() if int(count) < target}
print(f"verified grasp counts: {counts}")
if missing:
    print(f"Missing target counts: {missing}")
    sys.exit(1)
PY

