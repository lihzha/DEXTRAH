      --grasp_reset_ik_damping "$GRASP_RESET_IK_DAMPING"
      --grasp_reset_ik_max_joint_step "$GRASP_RESET_IK_MAX_JOINT_STEP"
      --grasp_reset_ik_pos_tolerance "$GRASP_RESET_IK_POS_TOLERANCE"
      --grasp_reset_ik_rot_tolerance "$GRASP_RESET_IK_ROT_TOLERANCE"
      --grasp_pregrasp_offset "$GRASP_PREGRASP_OFFSET"
      --grasp_warmstart_close_width "$GRASP_WARMSTART_CLOSE_WIDTH"
      --grasp_warmstart_prior_close_width_margin "$GRASP_WARMSTART_PRIOR_CLOSE_WIDTH_MARGIN"
      --grasp_warmstart_min_close_width "$GRASP_WARMSTART_MIN_CLOSE_WIDTH"
      --grasp_warmstart_lift_action_z "$GRASP_WARMSTART_LIFT_ACTION_Z"
      --grasp_warmstart_approach_steps "$GRASP_WARMSTART_APPROACH_STEPS"
